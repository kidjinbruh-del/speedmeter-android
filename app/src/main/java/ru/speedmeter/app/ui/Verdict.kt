package ru.speedmeter.app.ui

/**
 * Что сказать о достоверности замера.
 *
 * Цифры могут быть верными, а канал — плохим. Тогда результат честный, но
 * для сравнения с тарифным планом бесполезный: замер за 30 секунд на
 * канале, который дважды замирал по секунде, показывает среднее, которого
 * в жизни не бывает. Об этом лучше сказать прямо, чем молча показать
 * «27 Мбит/с» рядом с задержкой в две секунды.
 *
 * Пороги подобраны по смыслу, а не по красоте цифр:
 *  * 300 мс — «дальше секунды»: для домашнего Wi-Fi это уже плохо;
 *  * 1000 мс — половина замеров не дождалась ответа;
 *  * джиттер от 300 мс — канал гуляет сильнее, чем его средняя задержка.
 */
fun qualityNote(pingMs: Double, jitterMs: Double): String? = when {
    pingMs <= 0.0 -> "Задержку измерить не удалось: сервер не ответил"
    pingMs >= 1000.0 ->
        "Сеть очень нестабильна: задержка больше секунды, цифры приблизительные"
    jitterMs >= 300.0 ->
        "Замер нестабилен: джиттер ${formatMs(jitterMs)}. Лучше повторить в спокойную минуту"
    pingMs >= 300.0 ->
        "Задержка большая (${formatMs(pingMs)}): канал загружен или сервер далеко"
    else -> null
}